import typescript from "@rollup/plugin-typescript";
import { nodeResolve } from "@rollup/plugin-node-resolve";
import rollupJson from "@rollup/plugin-json";
import commonjs from "@rollup/plugin-commonjs";
import { mkdirSync, copyFileSync } from "fs";
import path from "path";

const isProd = process.env.BUILD === "production";

const currentDir = path.dirname(__filename);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ROLLUP
if you want to view the source visit the plugins github repository
*/
`;

export default {
  input: "src/main.ts",
  output: {
    dir: "obsidian_local_images_plus_latest",
    sourcemap: "inline",
    sourcemapExcludeSources: isProd,
    format: "cjs",
    exports: "default",
    banner,
  },
  external: ["obsidian"],
  plugins: [
    {
      name: "copy-plugin-assets",
      buildStart() {
        const outputDir = path.join(currentDir, "obsidian_local_images_plus_latest");
        mkdirSync(outputDir, { recursive: true });
        for (const asset of ["manifest.json", "styles.css"]) {
          copyFileSync(path.join(currentDir, asset), path.join(outputDir, asset));
        }
      },
    },
    typescript(),
    nodeResolve({ browser: true }),
    rollupJson(),
    commonjs(),
  ],
  onwarn(warning, warn) {
    // workaround to prevent rollup build error
    if (
      warning.code === "EVAL" &&
      /.*\/node_modules\/file-type\/.*/.test(warning.loc.file)
    ) {
      return;
    }
    warn(warning);
  },
};
